#!/usr/bin/env node
/**
 * Generate the file:// friendly JS mirror of the canonical JSON data.
 *
 *   node scripts/build-data.mjs
 *
 * GitHub Pages uses data/family-tree.json directly. The generated JS mirror
 * means the page also works if someone opens index.html from disk, where
 * fetch() is usually blocked by the browser.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = path.join(root, 'data', 'family-tree.json');
const jsPath = path.join(root, 'data', 'family-tree.js');

const source = await readFile(jsonPath, 'utf8');
const data = JSON.parse(source);

// Re-stringify with the same two-space formatting used by the source data.
const pretty = JSON.stringify(data, null, 2);
const banner = `/* Generated from data/family-tree.json by scripts/build-data.mjs.\n   Do not edit this file directly; edit the JSON and regenerate. */\n`;
await writeFile(jsPath, `${banner}window.FAMILY_TREE_DATA = ${pretty};\n`, 'utf8');

console.log(`Wrote ${path.relative(root, jsPath)} (${data.nodes.length} boards, ${data.links.length} links).`);
